//! src/kernel/drivers/framebuffer_console.rs
//!
//! Text console rendered over a framebuffer.
//! Framebuffer text console renderer.
//!
//! Renders a fixed-width character grid on top of the bochs-display linear
//! framebuffer.  Provides scrolling, a hardware-style blinking cursor, and
//! minimal control-character handling.
//!
//! Uses an original 8×16 bitmap font (ASCII 0x20–0x7E, 95 glyphs).  Each
//! glyph is 16 bytes — one byte per row, MSB = leftmost pixel.  Characters
//! outside the printable ASCII range render as a dotted fallback glyph.
//!
//! The font is original work created for this project.  Source of truth:
//! `tools/generate_font.py` — run `python3 tools/generate_font.py` to
//! regenerate the glyph table.

