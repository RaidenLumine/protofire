def glyph_to_bytes(rows):
    """Convert 8×16 ASCII-art rows to 16 bytes (MSB = leftmost pixel)."""
    result = []
    for row in rows:
        assert len(row) == 8, f"row must be exactly 8 chars, got {len(row)}: {row!r}"
        byte = 0
        for i, ch in enumerate(row):
            if ch == '#':
                byte |= 0x80 >> i
            elif ch != '.':
                raise ValueError(f"Unexpected char {ch!r} in glyph row {row!r}")
        result.append(byte)
    assert len(result) == 16, f"glyph must have exactly 16 rows, got {len(result)}"
    return result


def generate_rust_array():
    """Generate the Rust static FONT_DATA array."""
    # Process glyphs in order 0x20..0x7E
    all_bytes = []
    for code in range(0x20, 0x7F):
        rows = GLYPHS[code]
        glyph_bytes = glyph_to_bytes(rows)
        all_bytes.extend(glyph_bytes)

    # Format as Rust array
    lines = []
    lines.append("//! This font is original work created for the protofire kernel project.")
    lines.append("//!")
    lines.append("//! Source of truth: tools/generate_font.py")
    lines.append("//! Generate with: python3 tools/generate_font.py")
    lines.append("")
    lines.append("/// Glyph data: 16 bytes per character, one byte per row (MSB = leftmost).")
    lines.append("const FONT_GLYPH_HEIGHT: usize = 16;")
    lines.append("const FONT_GLYPH_WIDTH: usize = 8;")
    lines.append("const FONT_GLYPH_BYTES: usize = 16;")
    lines.append("const FONT_FIRST: u8 = 0x20; // space")
    lines.append("const FONT_LAST: u8 = 0x7E;  // tilde")
    lines.append("")
    lines.append("#[rustfmt::skip]")
    glyph_count = 0x7F - 0x20
    total = glyph_count * 16
    lines.append(
        f"static FONT_DATA: &[u8; {glyph_count} * FONT_GLYPH_BYTES] = &["
    )

    # Group by glyph, printing 8 bytes per line for readability
    byte_strs = [f"0x{b:02X}" for b in all_bytes]
    for glyph_idx in range(glyph_count):
        ch = chr(0x20 + glyph_idx)
        name = {
            0x20: "space", 0x21: "!", 0x22: '"', 0x23: "#", 0x24: "$",
            0x25: "%", 0x26: "&", 0x27: "'", 0x28: "(", 0x29: ")",
            0x2A: "*", 0x2B: "+", 0x2C: ",", 0x2D: "-", 0x2E: ".",
            0x2F: "/",
        }.get(0x20 + glyph_idx, chr(0x20 + glyph_idx))
        if name == '"':
            name = '\'"\''

        start = glyph_idx * 16
        row_bytes = byte_strs[start : start + 16]
        # 8 bytes per line, 2 lines per glyph
        line1 = ",".join(row_bytes[0:8])
        line2 = ",".join(row_bytes[8:16])
        lines.append(f"    // 0x{0x20 + glyph_idx:02X} {name}")
        lines.append(f"    {line1},")
        lines.append(f"    {line2},")

    lines.append("];")
    return "\n".join(lines)


